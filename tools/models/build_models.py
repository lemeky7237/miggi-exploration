"""Builds the four monster models: Java layer definitions + matching box-UV textures + preview renders.

  python3 build_models.py <repo-root> [--preview <dir>]

Everything about a model lives in specs.py (parts, boxes, materials, face decorations). This script
1. snaps every box to a 0.25 grid (so UVs land on whole texture pixels at 4 px per unit),
2. packs each box's UV island into the atlas,
3. paints the faces (painter.py materials + per-box decor),
4. writes src/client/java/.../client/mobs/MobLayers.java and textures/entity/<mob>.png,
5. optionally renders front / three-quarter / side previews with a tiny software renderer.
"""
import math, os, sys
import numpy as np
from PIL import Image, ImageDraw

sys.path.insert(0, os.path.dirname(__file__))
from painter import S
import specs

GRID = 0.25


def snap(v):
    return round(v / GRID) * GRID


# ------------------------------------------------------------------ packing
def pack(boxes, width_units):
    """Shelf-pack UV islands. Each island is (2*(d+w)) x (d+h) units."""
    order = sorted(boxes, key=lambda b: -(b.d + b.h))
    x = y = shelf = 0
    for b in order:
        iw = math.ceil(2 * (b.d + b.w)) + 1
        ih = math.ceil(b.d + b.h) + 1
        if x + iw > width_units:
            x = 0
            y += shelf
            shelf = 0
        b.u, b.v = x, y
        x += iw
        shelf = max(shelf, ih)
    used_h = y + shelf
    h = 32
    while h < used_h:
        h *= 2
    return h


def faces(b):
    """(name, u0, v0, fw, fh) in units, Minecraft box-UV layout."""
    u, v, w, h, d = b.u, b.v, b.w, b.h, b.d
    return [
        ("top", u + d, v, w, d),
        ("bottom", u + d + w, v, w, d),
        ("right", u, v + d, d, h),
        ("front", u + d, v + d, w, h),
        ("left", u + d + w, v + d, d, h),
        ("back", u + d + w + d, v + d, w, h),
    ]


def paint_atlas(model, tw, th):
    img = np.zeros((th * S, tw * S, 4), np.float32)
    for part in model.parts:
        for i, b in enumerate(part.boxes):
            for (name, fu, fv, fw, fh) in faces(b):
                pw, ph = int(round(fw * S)), int(round(fh * S))
                if pw <= 0 or ph <= 0:
                    continue
                face = b.mat.paint(pw, ph, name, (model.name, part.name, i))
                if b.decor:
                    b.decor(face, name)
                x0, y0 = int(round(fu * S)), int(round(fv * S))
                img[y0:y0 + ph, x0:x0 + pw] = face[:ph, :pw]
    # bleed colours 2 px into empty texels so nearest-sampling at island edges never hits a hole
    from scipy import ndimage
    for _ in range(2):
        a = img[..., 3] > 0.5
        if a.all():
            break
        idx = ndimage.distance_transform_edt(~a, return_distances=False, return_indices=True)
        filled = img[idx[0], idx[1]]
        grow = ndimage.binary_dilation(a) & ~a
        img[grow] = filled[grow]
        img[grow, 3] = 1.0
    return Image.fromarray((np.clip(img, 0, 1) * 255).astype(np.uint8), "RGBA")


# ------------------------------------------------------------------ java
def jf(v):
    s = ("%.4f" % v).rstrip("0").rstrip(".")
    if s in ("-0", ""):
        s = "0"
    return s + "f"


def java_layer(model, tw, th):
    out = [f"    public static LayerDefinition {model.method}() {{",
           "        MeshDefinition mesh = new MeshDefinition();",
           "        PartDefinition root = mesh.getRoot();"]
    for p in model.parts:
        parent = "root" if p.parent is None else "p_" + p.parent
        cubes = "CubeListBuilder.create()"
        for b in p.boxes:
            cubes += f".texOffs({b.u}, {b.v}).addBox({jf(b.x)}, {jf(b.y)}, {jf(b.z)}, {jf(b.w)}, {jf(b.h)}, {jf(b.d)})"
        px, py, pz = p.pivot
        rx, ry, rz = p.rot
        if rx or ry or rz:
            pose = f"PartPose.offsetAndRotation({jf(px)}, {jf(py)}, {jf(pz)}, {jf(rx)}, {jf(ry)}, {jf(rz)})"
        else:
            pose = f"PartPose.offset({jf(px)}, {jf(py)}, {jf(pz)})"
        out.append(f"        PartDefinition p_{p.name} = {parent}.addOrReplaceChild(\"{p.name}\", {cubes}, {pose});")
    out.append(f"        return LayerDefinition.create(mesh, {tw}, {th});")
    out.append("    }")
    return "\n".join(out)


