# ------------------------------------------------------------------ preview renderer
def rot_matrix(rx, ry, rz):
    cx, sx = math.cos(rx), math.sin(rx)
    cy, sy = math.cos(ry), math.sin(ry)
    cz, sz = math.cos(rz), math.sin(rz)
    Rx = np.array([[1, 0, 0], [0, cx, -sx], [0, sx, cx]])
    Ry = np.array([[cy, 0, sy], [0, 1, 0], [-sy, 0, cy]])
    Rz = np.array([[cz, -sz, 0], [sz, cz, 0], [0, 0, 1]])
    return Rz @ Ry @ Rx


def world_transforms(model, pose_override=None):
    T = {}
    for p in model.parts:
        rot = p.rot
        if pose_override and p.name in pose_override:
            rot = tuple(a + b for a, b in zip(rot, pose_override[p.name]))
        M = np.eye(4)
        M[:3, :3] = rot_matrix(*rot)
        M[:3, 3] = p.pivot
        T[p.name] = M if p.parent is None else T[p.parent] @ M
    return T


def box_face_quads(b):
    x0, y0, z0 = b.x, b.y, b.z
    x1, y1, z1 = x0 + b.w, y0 + b.h, z0 + b.d
    # corners listed as (top-left, top-right, bottom-left) of the texture face image
    return {
        "front": ((x0, y0, z0), (x1, y0, z0), (x0, y1, z0)),
        "back": ((x1, y0, z1), (x0, y0, z1), (x1, y1, z1)),
        "right": ((x0, y0, z1), (x0, y0, z0), (x0, y1, z1)),
        "left": ((x1, y0, z0), (x1, y0, z1), (x1, y1, z0)),
        "top": ((x0, y0, z1), (x1, y0, z1), (x0, y0, z0)),
        "bottom": ((x0, y1, z0), (x1, y1, z0), (x0, y1, z1)),
    }


def render_preview(model, atlas, yaw_deg, size=520, pose=None, light=True):
    T = world_transforms(model, pose)
    yaw = math.radians(yaw_deg)
    # view: model y down -> screen y down; look from -z (front) rotated by yaw around y
    Ry = np.array([[math.cos(yaw), 0, math.sin(yaw)], [0, 1, 0], [-math.sin(yaw), 0, math.cos(yaw)]])
    pitch = math.radians(-12)
    Rx = np.array([[1, 0, 0], [0, math.cos(pitch), -math.sin(pitch)], [0, math.sin(pitch), math.cos(pitch)]])
    V = Rx @ Ry
    polys = []
    pts_all = []
    for p in model.parts:
        M = T[p.name]
        for i, b in enumerate(p.boxes):
            q = box_face_quads(b)
            fmap = {n: (fu, fv, fw, fh) for (n, fu, fv, fw, fh) in faces(b)}
            for name, (a, bb, c) in q.items():
                P = [(M @ np.array([*pt, 1]))[:3] for pt in (a, bb, c)]
                Pv = [V @ pt for pt in P]
                n = np.cross(Pv[1] - Pv[0], Pv[2] - Pv[0])
                if np.linalg.norm(n) < 1e-9:
                    continue
                n = n / np.linalg.norm(n)
                if n[2] < 0:  # facing away (model y points down, so outward normals come out flipped)
                    continue
                d = Pv[1] + Pv[2] - Pv[0]
                depth = (Pv[0][2] + Pv[1][2] + Pv[2][2] + d[2]) / 4
                polys.append((depth, Pv, fmap[name], n))
                pts_all += [Pv[0][:2], Pv[1][:2], Pv[2][:2], d[:2]]
    pts_all = np.array(pts_all)
    lo, hi = pts_all.min(0), pts_all.max(0)
    scale = (size * 0.86) / max(hi - lo)
    off = np.array([size / 2, size / 2]) - (lo + hi) / 2 * scale
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    ldir = np.array([0.4, -0.8, -0.45])
    ldir /= np.linalg.norm(ldir)
    for depth, Pv, (fu, fv, fw, fh), n in sorted(polys, key=lambda t: -t[0]):
        pw, ph = int(round(fw * S)), int(round(fh * S))
        if pw <= 0 or ph <= 0:
            continue
        tex = atlas.crop((int(round(fu * S)), int(round(fv * S)), int(round(fu * S)) + pw, int(round(fv * S)) + ph))
        if light:
            k = 0.55 + 0.45 * max(0.0, float(-(n @ ldir)))
            arr = np.asarray(tex, np.float32)
            arr[..., :3] *= k
            tex = Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8), "RGBA")
        A = Pv[0][:2] * scale + off
        B = Pv[1][:2] * scale + off
        C = Pv[2][:2] * scale + off
        # affine: screen = A + (B-A)*(tx/pw) + (C-A)*(ty/ph) ; PIL wants inverse (screen -> tex)
        Mx = np.array([[(B - A)[0] / pw, (C - A)[0] / ph], [(B - A)[1] / pw, (C - A)[1] / ph]])
        if abs(np.linalg.det(Mx)) < 1e-9:
            continue
        inv = np.linalg.inv(Mx)
        a, b_, c_ = inv[0, 0], inv[0, 1], -(inv[0] @ A)
        d_, e, f = inv[1, 0], inv[1, 1], -(inv[1] @ A)
        warped = tex.transform((size, size), Image.AFFINE, (a, b_, c_, d_, e, f), resample=Image.NEAREST)
        mask = Image.new("L", (size, size), 0)
        ImageDraw.Draw(mask).polygon([tuple(A), tuple(B), tuple(B + C - A), tuple(C)], fill=255)
        wa = np.minimum(np.asarray(warped.split()[3]), np.asarray(mask))
        warped.putalpha(Image.fromarray(wa))
        canvas.alpha_composite(warped)
    return canvas


def main():
    root = sys.argv[1]
    preview = None
    if "--preview" in sys.argv:
        preview = sys.argv[sys.argv.index("--preview") + 1]
        os.makedirs(preview, exist_ok=True)
    java = [JAVA_HEADER]
    for model in specs.MODELS:
        for p in model.parts:
            p.pivot = tuple(snap(v) for v in p.pivot)
            for b in p.boxes:
                b.x, b.y, b.z = snap(b.x), snap(b.y), snap(b.z)
                b.w, b.h, b.d = max(GRID, snap(b.w)), max(GRID, snap(b.h)), max(GRID, snap(b.d))
        boxes = [b for p in model.parts for b in p.boxes]
        tw = model.tex_width
        th = pack(boxes, tw)
        atlas = paint_atlas(model, tw, th)
        tex_path = os.path.join(root, "src/main/resources/assets/miggi_exploration/textures/entity", model.name + ".png")
        atlas.save(tex_path)
        java.append(java_layer(model, tw, th) + "\n")
        print(f"{model.name}: {len(model.parts)} parts, {len(boxes)} boxes, texture {tw}x{th} units -> {atlas.size}")
        if preview:
            views = [render_preview(model, atlas, y) for y in (0, 35, 90, 180)]
            sheet = Image.new("RGBA", (520 * 4, 520), (150, 175, 205, 255))
            for i, v in enumerate(views):
                sheet.alpha_composite(v, (520 * i, 0))
            sheet.save(os.path.join(preview, model.name + "_views.png"))
            for pname, pose in model.preview_poses.items():
                v = render_preview(model, atlas, 30, pose=pose)
                bg = Image.new("RGBA", v.size, (150, 175, 205, 255))
                bg.alpha_composite(v)
                bg.save(os.path.join(preview, f"{model.name}_pose_{pname}.png"))
    java.append("}\n")
    out = os.path.join(root, "src/client/java/com/miggi/exploration/client/mobs/MobLayers.java")
    open(out, "w").write("\n".join(java))


if __name__ == "__main__":
    main()
